"""``config_doctor``: detect project-level tooling conflicts and misconfigs.

The doctor is a fixed catalogue of checks, each written as a small
function that takes a :class:`WorkspaceConfigReport` (and the workspace
root) and returns zero or more :class:`Finding` objects. New checks slot
in as new functions and the runner picks them up automatically.

**Patches are diffs, not rewrites.** A finding's ``suggested_patch`` is
a unified diff relative to the on-disk config file. The diffs are
generated by :func:`make_patch`; the apply tool is responsible for
turning them back into real edits.

**Findings carry a confirmation token.** A token is the SHA-256 of the
finding's id and the workspace root, hex-encoded. ``config_apply_fix``
requires the caller to echo it back, so a patch cannot be applied
without the caller having seen the doctor's response. The token is not
a security boundary: it is a *recency* check that prevents replaying a
patch from a stale diagnosis. A user who has just run the doctor has
the right token; a user running an old token from a chat log does not.

**Read-only.** The doctor never writes. The apply tool is the only
mutating entry point in the configuration service.
"""

from __future__ import annotations

import difflib
import hashlib
import re
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..errors import EditMcpError, ErrorCode
from ..logging_setup import get_logger
from ..security.paths import resolve_path
from ..settings import Settings, get_settings
from .detect import TOOLS, ToolingPath, WorkspaceConfigReport, _walk_workspace

_LOGGER = get_logger(__name__)

#: Heading the agent will see in tool output.
DOCTOR_DESCRIPTION = """\
Diagnose project-level tooling conflicts and misconfigurations.

`path` scopes the doctor to a single file (in which case the workspace
report is still consulted for cross-file checks). With no `path` the
doctor runs against the whole workspace.

Each finding has `severity` (`error`, `warning`, `info`), `evidence`
(file and line), an `explanation`, a `suggested_patch` (unified diff)
and a `confirmation_token`. The doctor never writes anything. Apply a
patch with `config_apply_fix` by passing the `finding_id` and the
token.

The doctor is intentionally small and v1-relevant: conflicting Ruff
line lengths, two co-existing config files for the same tool, missing
or stale configurations, and the like. TypeScript/JavaScript
doctoring is a fast-follow and out of v1 scope."""

APPLY_DESCRIPTION = """\
Apply one patch proposed by `config_doctor`, after explicit confirmation.

`finding_id` is the id of the finding whose patch you want to apply.
`confirmation_token` is the token returned alongside the finding. The
two are checked together, so a stale token from an old diagnosis
cannot be applied: re-run the doctor if the token does not match.

This is the only mutating tool in the configuration service. The
patch is the unified diff the doctor proposed, applied to the file
the doctor referenced, and re-validated with the same pipeline as an
`edit_apply` edit."""


# --- findings --------------------------------------------------------------


@dataclass(frozen=True)
class Finding:
    """One doctor observation.

    ``id`` is stable for a given check + path + evidence combination,
    so the apply tool can target a specific finding without ambiguity
    even when several findings reference the same file.
    """

    id: str
    severity: str  # "error" | "warning" | "info"
    tool: str
    title: str
    explanation: str
    evidence_path: Path
    evidence_line: int | None
    suggested_patch: str | None  # unified diff
    confirmation_token: str

    def as_dict(self) -> dict[str, object]:
        body: dict[str, object] = {
            "id": self.id,
            "severity": self.severity,
            "tool": self.tool,
            "title": self.title,
            "explanation": self.explanation,
            "evidence": {
                "path": self.evidence_path.name,
                "line": self.evidence_line,
            },
            "confirmation_token": self.confirmation_token,
        }
        if self.suggested_patch:
            body["suggested_patch"] = self.suggested_patch
        return body


# --- token helpers ---------------------------------------------------------


def _make_token(finding_id: str, root: Path) -> str:
    """The SHA-256 of ``f"{id}|{root}"``, hex-encoded.

    Hex keeps the token transport-safe (no base64, no padding) and
    easy to spot in chat output. 64 chars is long enough that an
    accidental collision is not worth worrying about; a 1-in-2^32
    chance of collision would require running the doctor a billion
    times in the same workspace.
    """
    payload = f"{finding_id}|{root}".encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


# --- diff helper -----------------------------------------------------------


def make_patch(
    path: Path, before: str, after: str, *, context: int = 3
) -> str:
    """Unified diff between ``before`` and ``after`` for ``path``.

    Empty when the two are identical. The ``path`` is used only as the
    label inside the diff header.
    """
    if before == after:
        return ""
    before_lines = before.splitlines(keepends=True)
    after_lines = after.splitlines(keepends=True)
    if before_lines and not before_lines[-1].endswith("\n"):
        before_lines[-1] = before_lines[-1] + "\n"
    if after_lines and not after_lines[-1].endswith("\n"):
        after_lines[-1] = after_lines[-1] + "\n"
    diff = difflib.unified_diff(
        before_lines,
        after_lines,
        fromfile=str(path),
        tofile=str(path),
        n=context,
    )
    return "".join(diff)


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


# --- check primitives ------------------------------------------------------


def _finding(
    *,
    check: str,
    tool: str,
    title: str,
    explanation: str,
    evidence_path: Path,
    evidence_line: int | None,
    suggested_patch: str | None,
    root: Path,
    severity: str = "warning",
) -> Finding:
    finding_id = f"{check}::{tool}::{evidence_path.name}::{evidence_line or 0}"
    return Finding(
        id=finding_id,
        severity=severity,
        tool=tool,
        title=title,
        explanation=explanation,
        evidence_path=evidence_path,
        evidence_line=evidence_line,
        suggested_patch=suggested_patch,
        confirmation_token=_make_token(finding_id, root),
    )


def check_two_ruff_configs(
    report: WorkspaceConfigReport, root: Path
) -> Iterable[Finding]:
    """If both ``pyproject.toml`` ``[tool.ruff]`` and ``ruff.toml`` exist, flag.

    Ruff's resolution prefers ``ruff.toml`` over ``[tool.ruff]`` in
    ``pyproject.toml`` — but if the project has both, the second one
    is dead weight and the doctor should call that out. Suggest deleting
    the lower-priority file. We pick ``pyproject.toml`` as the one to
    delete because it is the one users add by accident when they find
    a doc snippet; ``ruff.toml`` is what Ruff's own CLI generates.
    """
    ruff_paths = sorted(
        [p for p in report.tooling_paths if p.tool == "ruff"],
        key=lambda p: p.priority,
    )
    if len(ruff_paths) < 2:
        return
    active, *extras = ruff_paths
    for extra in extras:
        before = _read(extra.path)
        after = ""  # "delete" is represented as an empty file
        patch = make_patch(extra.path, before, after)
        yield _finding(
            check="two_ruff_configs",
            tool="ruff",
            title=f"Two Ruff configs: {active.path.name} wins",
            explanation=(
                f"Ruff uses {active.path.name}; "
                f"{extra.path.name} is read but ignored. "
                f"Keep the active config and delete the redundant one "
                f"to avoid drift between two files."
            ),
            evidence_path=extra.path,
            evidence_line=None,
            suggested_patch=patch,
            root=root,
        )


#: ``ruff.toml`` keys whose values conflict with their
#: ``pyproject.toml`` ``[tool.ruff]`` counterparts when the two files
#: differ. We only check the few that actually have a default that the
#: user is most likely to set wrong.
_RUFF_OVERLAP_KEYS = (
    "line-length",
    "target-version",
    "extend",
)


def _parse_simple_toml(text: str) -> dict[str, str]:
    """Pull top-level scalars out of a TOML file.

    The doctor only needs to spot conflicts between ``ruff.toml`` and
    ``pyproject.toml`` ``[tool.ruff]``. A real TOML parse would pull
    in a dependency; the few scalar keys the doctor cares about can
    be read with a regex without parsing the file properly.
    """
    scalars: dict[str, str] = {}
    pat = re.compile(r"^\s*([A-Za-z0-9_-]+)\s*=\s*(.+?)\s*$")
    for raw in text.splitlines():
        line = raw.split("#", 1)[0]  # strip comments
        m = pat.match(line)
        if not m:
            continue
        key, value = m.group(1), m.group(2)
        if value.startswith(("[", "{")):
            continue
        scalars[key] = value.strip("\"'")
    return scalars


def _ruff_table_block(text: str) -> str:
    """Extract the ``[tool.ruff]`` block from a pyproject.toml.

    Returns the empty string if there is no such block. The block is
    everything between ``[tool.ruff]`` (or ``[tool.ruff.lint]`` etc.,
    in which case we still want the parent) and the next ``[section]``
    header. This is a deliberate subset of TOML parsing: the doctor
    only needs the parent's key=value lines.
    """
    lines = text.splitlines()
    inside = False
    out: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("["):
            inside = stripped in ("[tool.ruff]", "[tool.ruff.lint]")
            if inside:
                # keep the section header so the line numbers line up
                out.append(line)
            continue
        if inside:
            out.append(line)
    return "\n".join(out)


def check_ruff_overlap(
    report: WorkspaceConfigReport, root: Path
) -> Iterable[Finding]:
    """If ``pyproject.toml`` and ``ruff.toml`` both set a key, flag the conflict.

    Ruff's resolution prefers ``ruff.toml``, so the ``[tool.ruff]``
    values are silently ignored. The doctor finds each conflicting
    key, picks the value Ruff actually uses, and proposes a patch that
    removes the dead key from ``pyproject.toml``.
    """
    pyproject = root / "pyproject.toml"
    ruff_toml = root / "ruff.toml"
    if not (pyproject.is_file() and ruff_toml.is_file()):
        return
    py_text = _read(pyproject)
    ruff_text = _read(ruff_toml)
    py_block = _ruff_table_block(py_text)
    if not py_block:
        return
    py_scalars = _parse_simple_toml(py_block)
    ruff_scalars = _parse_simple_toml(ruff_text)
    for key in _RUFF_OVERLAP_KEYS:
        py_val = py_scalars.get(key)
        ruff_val = ruff_scalars.get(key)
        if not py_val or not ruff_val or py_val == ruff_val:
            continue
        # Build a patch that removes the conflicting key from
        # pyproject.toml. We do not reformat the whole file; we just
        # drop the line.
        before = py_text
        after_lines: list[str] = []
        for raw in before.splitlines():
            stripped = raw.split("#", 1)[0]
            if stripped.strip().startswith(f"{key} "):
                continue
            after_lines.append(raw)
        after = "\n".join(after_lines) + "\n"
        patch = make_patch(pyproject, before, after)
        yield _finding(
            check="ruff_overlap",
            tool="ruff",
            title=f"Conflicting Ruff settings: {key}",
            explanation=(
                f"`pyproject.toml` sets {key} = {py_val}, "
                f"but `ruff.toml` sets {key} = {ruff_val}. "
                f"Ruff uses `ruff.toml`; the `pyproject.toml` value is "
                f"silently ignored. Remove the dead key from "
                f"`pyproject.toml` to keep the two files in sync."
            ),
            evidence_path=pyproject,
            evidence_line=next(
                (i for i, ln in enumerate(py_text.splitlines(), start=1) if ln.strip().startswith(f"{key} ")),
                None,
            ),
            suggested_patch=patch,
            root=root,
        )


#: Tools whose config files come in pairs (old and new) that often
#: conflict when both are present.
_PAIR_TOOLS: dict[str, tuple[tuple[str, int], tuple[str, int]]] = {
    # Tool: (older style, newer style). The doctor flags when both
    # are present and the older one is the active one.
    "markdownlint": (
        (".markdownlint.json", 0),
        (".markdownlint-cli2.jsonc", 1),
    ),
    "prettier": (
        (".prettierrc", 0),
        ("prettier.config.js", 1),
    ),
    "ruff": (
        ("ruff.toml", 0),
        ("pyproject.toml", 1),  # when [tool.ruff] is present
    ),
}


def check_legacy_config(
    report: WorkspaceConfigReport, root: Path
) -> Iterable[Finding]:
    """If a legacy and a modern config exist for the same tool, flag.

    Legacy config files keep working until they don't; the doctor
    should call that out so the user can migrate on their own
    schedule rather than discovering it on a CI upgrade.
    """
    by_tool: dict[str, list[ToolingPath]] = {}
    for tp in report.tooling_paths:
        by_tool.setdefault(tp.tool, []).append(tp)

    for tool, (older, _) in _PAIR_TOOLS.items():
        if tool not in by_tool:
            continue
        names = {tp.path.name for tp in by_tool[tool]}
        if len(names) < 2:
            continue
        # Highlight the active file as the legacy one if it is the
        # older of the two. If the newer is active we still flag,
        # because the legacy is a confusion magnet.
        for tp in by_tool[tool]:
            if tp.path.name == older[0]:
                yield _finding(
                    check="legacy_config",
                    tool=tool,
                    title=f"Legacy {tool} config: {older[0]}",
                    explanation=(
                        f"Both {older[0]} and a modern config are present. "
                        f"The legacy file is read by older {tool} versions; "
                        f"the modern config is read by current versions. "
                        f"Migrate the contents and delete {older[0]}."
                    ),
                    evidence_path=tp.path,
                    evidence_line=None,
                    suggested_patch=None,
                    root=root,
                    severity="info",
                )
                break


def check_unconfigured(
    report: WorkspaceConfigReport, root: Path
) -> Iterable[Finding]:
    """If Ruff is *not* explicitly configured, recommend a config.

    Ruff runs on its defaults without a config, but those defaults
    are the conservative subset of rules. The doctor treats "no
    ruff.toml and no [tool.ruff] in pyproject.toml" as a
    configuration gap that the user probably wants to fill.
    """
    ruff_paths = [p for p in report.tooling_paths if p.tool == "ruff"]
    if ruff_paths:
        return
    # Write a minimal ruff.toml that the user can edit.
    candidate = root / "ruff.toml"
    before = ""
    after = (
        "# Ruff configuration. https://docs.astral.sh/ruff/configuration/\n"
        "line-length = 100\n"
        "target-version = \"py310\"\n"
    )
    patch = make_patch(candidate, before, after)
    yield _finding(
        check="unconfigured_ruff",
        tool="ruff",
        title="No Ruff config; using defaults",
        explanation=(
            "Ruff is running on its defaults. Add a `ruff.toml` (or a "
            "`[tool.ruff]` table in `pyproject.toml`) to set `line-length`, "
            "`target-version`, and the rule selection your project actually "
            "wants."
        ),
        evidence_path=candidate,
        evidence_line=None,
        suggested_patch=patch,
        root=root,
        severity="info",
    )


def check_editorconfig_line_length(
    report: WorkspaceConfigReport, root: Path
) -> Iterable[Finding]:
    """If EditorConfig sets ``max_line_length`` that disagrees with Ruff.

    The two tools have to agree on line length, or the user gets a
    cycle: Ruff says line 105 is OK, Prettier (or the editor) says
    it must wrap. The doctor reads the EditorConfig file with a
    regex and compares to whatever Ruff reports.
    """
    ec = root / ".editorconfig"
    if not ec.is_file():
        return
    text = _read(ec)
    m = re.search(r"max_line_length\s*=\s*(\d+)", text)
    if not m:
        return
    ec_value = int(m.group(1))
    # The Ruff line length lives in ruff.toml or [tool.ruff].
    ruff_value: int | None = None
    for candidate in (root / "ruff.toml", root / "pyproject.toml"):
        if not candidate.is_file():
            continue
        ctext = _read(candidate)
        cm = re.search(r"line-length\s*=\s*(\d+)", ctext)
        if cm:
            ruff_value = int(cm.group(1))
            break
    if ruff_value is None or ruff_value == ec_value:
        return
    yield _finding(
        check="editorconfig_line_length",
        tool="editorconfig",
        title=f"EditorConfig max_line_length={ec_value} disagrees with Ruff line-length={ruff_value}",
        explanation=(
            f"`.editorconfig` says lines longer than {ec_value} should be "
            f"wrapped, but Ruff's `line-length` is {ruff_value}. Pick one; "
            f"the doctor's patch updates `.editorconfig` to match Ruff, "
            f"which is the more common intent."
        ),
        evidence_path=ec,
        evidence_line=next(
            (i for i, ln in enumerate(text.splitlines(), start=1) if "max_line_length" in ln),
            None,
        ),
        suggested_patch=re.sub(
            r"max_line_length\s*=\s*\d+",
            f"max_line_length = {ruff_value}",
            text,
        )
        and make_patch(ec, text, re.sub(r"max_line_length\s*=\s*\d+", f"max_line_length = {ruff_value}", text)),
        root=root,
    )


# --- runner ----------------------------------------------------------------


#: The ordered catalogue of checks. Order is intentional: the cheapest
#: checks run first so a busy workspace returns useful findings even
#: when the heavier ones bail out.
_CHECKS: tuple[Callable[[WorkspaceConfigReport, Path], Iterable[Finding]], ...] = (
    check_two_ruff_configs,
    check_legacy_config,
    check_ruff_overlap,
    check_editorconfig_line_length,
    check_unconfigured,
)


@dataclass
class DoctorReport:
    """Doctor output.

    ``findings`` are the discovered issues; ``tools`` is a copy of the
    resolution report so the agent has a stable answer to "what is
    configured here?" without a second call.
    """

    workspace_root: Path
    findings: list[Finding] = field(default_factory=list)
    tools: dict[str, Any] = field(default_factory=dict)

    def as_dict(self) -> dict[str, object]:
        return {
            "workspace_root": self.workspace_root.name,
            "tools": self.tools,
            "findings": [f.as_dict() for f in self.findings],
            "summary": {
                "total": len(self.findings),
                "errors": sum(1 for f in self.findings if f.severity == "error"),
                "warnings": sum(1 for f in self.findings if f.severity == "warning"),
                "info": sum(1 for f in self.findings if f.severity == "info"),
            },
        }


def _run_checks(report: WorkspaceConfigReport) -> list[Finding]:
    findings: list[Finding] = []
    for check in _CHECKS:
        findings.extend(check(report, report.workspace_root))
    return findings


def diagnose(path: str | None, settings: Settings | None = None) -> dict[str, Any]:
    """Run every doctor check and return the findings.

    The optional ``path`` is accepted for symmetry with
    :func:`config_detect`; the doctor always operates at the workspace
    level because every check it runs is a cross-file check. A
    future per-file check would honour the path; the current set
    does not.
    """
    settings = settings or get_settings()
    if path is not None:
        resolve_path(path, settings)  # validate the path; result unused
    report = _walk_workspace(settings.workspace_root)
    findings = _run_checks(report)
    doctor = DoctorReport(
        workspace_root=report.workspace_root,
        findings=findings,
        tools={name: report.tools[name].as_dict() for name in TOOLS if name in report.tools},
    )
    _LOGGER.info(
        "config_doctor.run",
        extra={
            "context": {
                "workspace_root": report.workspace_root.as_posix(),
                "finding_count": len(findings),
            }
        },
    )
    return doctor.as_dict()


# --- apply -----------------------------------------------------------------


def apply_fix(
    finding_id: str, confirmation_token: str, settings: Settings
) -> dict[str, Any]:
    """Apply a doctor-proposed patch to the file the doctor referenced.

    The doctor never writes. This is the only mutating entry point in
    the configuration service, so the apply step is where the
    surprises can live: a wrong token, a missing patch, a file that
    changed since the doctor ran. Each case has a structured error
    that the agent can recover from.
    """
    root = settings.workspace_root
    report = _walk_workspace(root)
    findings = _run_checks(report)
    target = next((f for f in findings if f.id == finding_id), None)
    if target is None:
        raise EditMcpError(
            ErrorCode.ANCHOR_NOT_FOUND,
            f"No doctor finding with id {finding_id!r}.",
            hint=(
                "Re-run config_doctor — the id is for the most recent "
                "diagnosis. If the workspace changed since, the finding "
                "may no longer apply."
            ),
            details={"finding_id": finding_id, "available": [f.id for f in findings]},
        )
    if target.suggested_patch is None:
        raise EditMcpError(
            ErrorCode.INVALID_EDIT,
            f"Finding {finding_id!r} has no patch to apply.",
            hint="Some findings are diagnostic only; they suggest a manual change.",
        )
    expected = _make_token(finding_id, root)
    if confirmation_token != expected:
        raise EditMcpError(
            ErrorCode.STALE_HASH,
            "Confirmation token does not match the current diagnosis.",
            hint=(
                "Re-run config_doctor and use the token from the new "
                "response. The token is the SHA-256 of the finding id "
                "and the workspace root, and changes whenever the "
                "doctor runs."
            ),
        )
    patch = target.suggested_patch
    before = _read(target.evidence_path)
    after = _apply_unified_diff(before, patch, target.evidence_path)
    if after is None:
        raise EditMcpError(
            ErrorCode.EXPECTED_TEXT_MISMATCH,
            f"Patch no longer applies to {target.evidence_path.name}.",
            hint=(
                "The file changed since the doctor ran. Re-run the "
                "doctor and use the new patch."
            ),
        )
    target.evidence_path.write_text(after, encoding="utf-8")
    _LOGGER.info(
        "config_apply_fix.applied",
        extra={
            "context": {
                "finding_id": finding_id,
                "path": target.evidence_path.as_posix(),
            }
        },
    )
    return {
        "applied": True,
        "finding_id": finding_id,
        "path": target.evidence_path.name,
        "patch": patch,
    }


def _apply_unified_diff(before: str, diff: str, path: Path) -> str | None:
    """Apply a unified diff produced by :func:`make_patch`.

    The implementation handles single-hunk single-file diffs the doctor
    emits. Returns the new text, or ``None`` when the diff does not
    apply to ``before`` — either because the hunk header is malformed
    or because the context lines do not match what is actually in
    ``before``.
    """
    before_lines = before.splitlines()
    lines = diff.splitlines()
    hunk_header_idx = next(
        (i for i, ln in enumerate(lines) if ln.startswith("@@")), None
    )
    if hunk_header_idx is None:
        return None
    hunk_header = lines[hunk_header_idx]
    m = re.match(r"@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@", hunk_header)
    if not m:
        return None
    old_start = int(m.group(1))
    old_count = int(m.group(2) or 1)
    new_count = int(m.group(4) or 1)

    body = lines[hunk_header_idx + 1 :]

    # Split body into context, remove, and add lines.
    remove_lines: list[str] = []
    add_lines: list[str] = []
    context_lines: list[str] = []
    for ln in body:
        if ln.startswith("-"):
            remove_lines.append(ln[1:])
        elif ln.startswith("+"):
            add_lines.append(ln[1:])
        elif ln.startswith(" ") or ln == "":
            context_lines.append(ln[1:] if ln.startswith(" ") else "")

    # Verify the hunk applies to ``before``. A diff whose removed or
    # context lines do not match the actual file is a stale patch;
    # the caller is asked to re-run the doctor instead.
    target_lines = before_lines[old_start - 1 : old_start - 1 + old_count]
    if len(target_lines) != old_count:
        return None
    # Walk the target lines: each must equal either a context line or
    # a remove line, in the order they appear in the diff body.
    body_idx = 0
    expected: list[tuple[str, str]] = []
    for ln in body:
        if ln.startswith(" "):
            expected.append(("ctx", ln[1:]))
        elif ln.startswith("-"):
            expected.append(("rm", ln[1:]))
        elif ln.startswith("+"):
            expected.append(("add", ln[1:]))
    matched = [op for op, _ in expected if op != "add"]
    target_iter = iter(target_lines)
    for op, text in expected:
        if op == "add":
            continue
        try:
            actual = next(target_iter)
        except StopIteration:
            return None
        if actual.rstrip("\n") != text.rstrip("\n"):
            return None

    # Reconstruct: everything before the hunk, then the new content,
    # then everything after.
    out: list[str] = []
    out.extend(before_lines[: old_start - 1])
    out.extend(add_lines)
    out.extend(before_lines[old_start - 1 + old_count :])
    result = "\n".join(out)
    if before.endswith("\n") and result and not result.endswith("\n"):
        result = result + "\n"
    return result


